/****************************************************************************************
* LICENSE POLICIES
****************************************************************************************/

CREATE POLICY "Users can view their own license"

ON public.licenses

FOR SELECT

TO authenticated

USING (
    auth.uid() = user_id
);

/****************************************************************************************
* DEVICE POLICIES
****************************************************************************************/

CREATE POLICY "Users can view their own devices"

ON public.licensed_devices

FOR SELECT

TO authenticated

USING (

    EXISTS (

        SELECT 1
        FROM public.licenses

        WHERE licenses.id = licensed_devices.license_id

        AND licenses.user_id = auth.uid()

    )

);

/****************************************************************************************
* AUDIT POLICIES
****************************************************************************************/

CREATE POLICY "Users can view their own license audit"

ON public.license_audit

FOR SELECT

TO authenticated

USING (

    EXISTS (

        SELECT 1
        FROM public.licenses

        WHERE licenses.id = license_audit.license_id

        AND licenses.user_id = auth.uid()

    )

);

